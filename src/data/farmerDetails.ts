const BY_KEY = Object.fromEntries(Object.entries(F).map(([k, v]) => [keyOf(k), v]))

/** Farmer-mode detail for a condition, or undefined if we have none. */
export function farmerInfo(info: ConditionInfo): FarmerInfo | undefined {
  if (info.severity === 'none') return HEALTHY_FARMER
  return BY_KEY[keyOf(`${info.crop} ${info.name}`)]
}
