#!/bin/zsh
# Move everything regenerable out of data/ once training and evaluation are done.
# Kept: original dataset archives (zip/7z/rar), wheat images (no archive exists), data/browser_view,
# lemon/PlantVillage/iBean sources, and each current model's metrics/splits/checkpoint.
# Nothing is deleted outright: it is moved to the Trash; empty the Trash to free the space.
set -e
cd "${0:A:h}/.."
if pgrep -f "training/.*(train|evaluate|stress_test|blur_compare|background_test).py" >/dev/null; then
  echo "training/evaluation still running; not cleaning"; exit 1
fi
# moved to the macOS Trash (empty it to free the space); nothing is deleted outright
HOLD=~/.Trash/cropguard-cleanup-$(date +%Y%m%d-%H%M)
mkdir -p "$HOLD"
mv_if() { [ -e "$1" ] && mkdir -p "$HOLD/$(dirname $1)" && mv "$1" "$HOLD/$1" && echo "moved $1" || true; }
# tf.data caches (decoded images; rebuilt automatically by the next training run)
for d in data/work_*/cache*(N) data/hp*/cache*(N); do mv_if "$d"; done  # incl. size-specific caches (cache_288)
# SavedModel intermediates (the shipped TF.js models live in public/models)
for d in data/work_*/savedmodel(N); do mv_if "$d"; done
# hyperparameter-search proxies: cache and trial checkpoints (results.json and logs stay)
for d in data/hp*/*/checkpoints(N); do mv_if "$d"; done
# superseded models: the shipped ones are in public/models and every earlier version is in git
for d in data/work_*/prev*(N) data/work_lemon_?(N); do mv_if "$d"; done
# NOTE: data/browser_view is kept: training reads browser-identical pixels from it
# stress-test image dumps (regenerated by training/stress_test.py)
for d in data/work_*/gate_samples*(N); do mv_if "$d"; done
# unzipped copies whose archive is kept (training/farm/download_datasets.py re-extracts)
for a in cassava cotton cotton_sarcld rice_riceleafbd rice_sethy sugarcane; do
  ls data/farm_raw/$a.* >/dev/null 2>&1 && mv_if data/farm_raw/$a
done
[ -e data/plantdoc.zip ] && mv_if data/plantdoc_raw
# retired models' work folders: keep split files (the crops dataset is built from
# work_garden/splits.csv, which comes from work_plantvillage/splits.csv) and checkpoints
for d in work_garden work_router work_plantvillage; do
  [ -d data/$d ] || continue
  for f in data/$d/*(N); do
    case "${f:t}" in splits.csv|split_report.json|dataset_report.json|metrics.json|checkpoints) ;; *) mv_if "$f" ;; esac
  done
done
du -sh data "$HOLD"
